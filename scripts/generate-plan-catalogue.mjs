import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root = new URL('../',import.meta.url);
const catalogue = JSON.parse(await readFile(new URL('shared/plan-catalogue.json',root),'utf8'));
const source = `// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by scripts/generate-plan-catalogue.mjs; edit shared/plan-catalogue.json.\nexport const PLAN_CATALOGUE = ${JSON.stringify(catalogue,null,2)} as const;\n`;
const targets=['src/lib/planCatalogue.ts','task-runner/src/planCatalogue.ts','supabase/functions/_shared/planCatalogue.ts','ee/planCatalogue.ts'];
if(process.argv.includes('--landing')) targets.push('crewform-landing/src/planCatalogue.ts');
for(const path of targets) {
 const target=new URL(path,root);
 if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8')!==source) throw Error(`Stale catalogue: ${fileURLToPath(target)}`);
 } else await writeFile(target,source);
}

const quote=value=>"'"+value.replaceAll("'","''")+"'";
let sql='-- SPDX-License-Identifier: AGPL-3.0-or-later\n-- Generated by scripts/generate-plan-catalogue.mjs; existing customer overrides remain intact.\n';
for(const [id,plan] of Object.entries(catalogue.plans)) for(const [resource,max] of Object.entries(plan.limits)) sql+=`INSERT INTO public.plan_limits(plan,resource,max_value) VALUES(${quote(id)},${quote(resource)},${max}) ON CONFLICT(plan,resource) DO UPDATE SET max_value=EXCLUDED.max_value;\n`;
sql+="CREATE OR REPLACE FUNCTION public.features_for_plan(p_plan text) RETURNS text[] LANGUAGE sql IMMUTABLE SET search_path='' AS $$ SELECT CASE p_plan\n";
for(const [id,plan] of Object.entries(catalogue.plans)) sql+=`WHEN ${quote(id)} THEN ARRAY[${[...catalogue.communityFeatures,...plan.features].map(quote).join(',')}]::text[]\n`;
sql+="ELSE ARRAY[]::text[] END $$;\n";
const target=new URL('supabase/migrations/091_plan_catalogue.sql',root);
if(process.argv.includes('--check')) {if(await readFile(target,'utf8')!==sql) throw Error('Stale SQL plan catalogue');} else await writeFile(target,sql);
